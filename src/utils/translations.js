/**
 * Helper to resolve dynamic bilingual objects or strings
 */
export const getBilingualText = (value, lang) => {
  if (!value) return '';
  if (typeof value === 'string') return value;
  if (typeof value === 'object') {
    return value[lang] || value.en || value.ar || '';
  }
  return String(value);
};
